"""Write isolated Tiny FP16 configs for one full-trainval experiment."""
import argparse
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--repo-root', type=Path, required=True)
    parser.add_argument('--task-root', type=Path, required=True)
    parser.add_argument('--data-root', type=Path, required=True)
    args = parser.parse_args()
    task = args.task_root.resolve()
    directory = task / 'configs'
    directory.mkdir(parents=True, exist_ok=True)
    base = args.repo_root.resolve() / 'projects/configs/bevformer_fp16/bevformer_tiny_fp16.py'
    if not base.is_file():
        raise FileNotFoundError(base)
    data = str(args.data_root.resolve()) + '/'
    infos = str(task / 'infos') + '/'
    train = f'''# Generated by make_configs.py. Full trainval, fresh ImageNet backbone.
_base_ = [{str(base)!r}]
custom_imports = dict(imports=['training_support'], allow_failed_imports=False)
data_root = {data!r}
info_root = {infos!r}
data = dict(
    samples_per_gpu=1, workers_per_gpu=2,
    train=dict(type='TrainvalNuScenesDataset', data_root=data_root,
               ann_file=info_root + 'nuscenes_infos_temporal_train.pkl'),
    val=dict(type='TrainvalNuScenesDataset', data_root=data_root,
             ann_file=info_root + 'nuscenes_infos_temporal_val.pkl', samples_per_gpu=1),
    test=dict(type='TrainvalNuScenesDataset', data_root=data_root,
              ann_file=info_root + 'nuscenes_infos_temporal_val.pkl', samples_per_gpu=1))
# Linear scaling: original lr 2.8e-4 at global batch 16 -> one GPU, batch 1.
optimizer = dict(lr=1.75e-5)
total_epochs = 24
runner = dict(max_epochs=24)
evaluation = dict(interval=1)
checkpoint_config = dict(interval=1, max_keep_ckpts=3)
log_config = dict(interval=50)
work_dir = {str(task / 'work_dirs/trainval')!r}
load_from = None
resume_from = None
custom_hooks = [
    dict(type='TransferWeight', priority='LOWEST'),
    dict(type='SyncHistoryBeforeRunHook', priority='LOWEST'),
    dict(type='TrainingHealthHook', interval=50, priority='LOWEST')]
'''
    smoke = f'''# Four real optimizer updates and three real validation frames.
_base_ = ['./tiny_trainval.py']
info_root = {infos!r}
data = dict(
    train=dict(ann_file=info_root + 'nuscenes_infos_temporal_smoke_train.pkl'),
    val=dict(type='TinySmokeNuScenesDataset',
             ann_file=info_root + 'nuscenes_infos_temporal_smoke_val.pkl'),
    test=dict(type='TinySmokeNuScenesDataset',
              ann_file=info_root + 'nuscenes_infos_temporal_smoke_val.pkl'))
total_epochs = 1
runner = dict(max_epochs=1)
lr_config = dict(warmup_iters=1)
log_config = dict(interval=1)
work_dir = {str(task / 'work_dirs/smoke')!r}
custom_hooks = [
    dict(type='TransferWeight', priority='LOWEST'),
    dict(type='SyncHistoryBeforeRunHook', priority='LOWEST'),
    dict(type='SmokeTrainingCheckHook', expected_steps=4, priority='LOWEST')]
'''
    for name, text in [('tiny_trainval.py', train), ('tiny_smoke.py', smoke)]:
        path = directory / name
        if path.exists() and path.read_text() != text:
            raise FileExistsError('Refusing to overwrite a different experiment config: ' + str(path))
        path.write_text(text, encoding='utf-8')
        print(path)


if __name__ == '__main__':
    main()
