def _fixture():
    config = BEVFormerFFNConfig()
    rng = np.random.default_rng(20261011)
    weights = {
        "fc1_weight": rng.normal(
            0.0, 0.02, (config.embed_dim, config.hidden_dim)
        ).astype(np.float32),
        "fc1_bias": rng.normal(0.0, 0.01, (config.hidden_dim,)).astype(
            np.float32
        ),
        "fc2_weight": rng.normal(
            0.0, 0.02, (config.hidden_dim, config.embed_dim)
        ).astype(np.float32),
        "fc2_bias": rng.normal(0.0, 0.01, (config.embed_dim,)).astype(
            np.float32
        ),
        "norm_weight": rng.normal(1.0, 0.02, (config.embed_dim,)).astype(
            np.float32
        ),
        "norm_bias": rng.normal(0.0, 0.01, (config.embed_dim,)).astype(
            np.float32
        ),
    }
    graph = build_bevformer_ffn_graph(weights, config)
    parameter_counts = dict(zip(PTX_ENTRY_SYMBOLS, (4, 3, 6), strict=True))
    entries = []
    for symbol in PTX_ENTRY_SYMBOLS:
        parameters = ",\n".join(
            f"  .param .u64 .ptr .global {symbol}_param_{index}"
            for index in range(parameter_counts[symbol])
        )
        entries.append(
            f".visible .entry {symbol}(\n{parameters}\n)\n"
            ".maxntid 256, 1, 1\n"
            "{ ret; }"
        )
    entry_source = "\n".join(entries)
    ptx = (
        "// Generated by LLVM NVPTX Back-End\n"
        ".version 7.1\n"
        ".target sm_86\n"
        ".address_size 64\n"
        f"{entry_source}\n"
    )

    def fake_lower(source, **_):
        # Mirror the real toolchain contract closely enough that the backend's
        # assembler independently re-extracts the PTX from gpu.binary.
        assembly = "".join(f"\\{byte:02X}" for byte in ptx.encode("utf-8"))
        return MlirPtxArtifact(
            command=("mlir-opt", "--gpu-lower-to-nvvm-pipeline=..."),
            mlir_opt_version="LLVM version 24.0.0git",
            mlir_opt_source_revision="a" * 40,
            source_sha256=hashlib.sha256(source.encode("utf-8")).hexdigest(),
            target_chip="sm_86",
            target_features="+ptx71",
            ptx_version="7.1",
            entries=PTX_ENTRY_SYMBOLS,
            binary_mlir=(
                "module {\n"
                "  gpu.binary @gac_bevformer_ffn "
                "[#gpu.object<#nvvm.target<chip = \\\"sm_86\\\">, "
                f'assembly = "{assembly}">>]\n'
                "}\n"
            ),
            ptx=ptx,
        )

    with patch(
        "gac.mlir_toolchain.lower_gpu_mlir_to_ptx", side_effect=fake_lower
    ):
        return compile_mlir_ptx(graph), graph


class _FakeContext:
    def __enter__(self):
        return self

    def __exit__(self, *_):
        return None


class _FakeStream(_FakeContext):
    def __init__(self):
        self.synchronize_calls = 0

    def synchronize(self):
        self.synchronize_calls += 1


class _FakeEvent:
    def __init__(self):
        self.recorded_streams: list[object] = []

    def record(self, stream):
        self.recorded_streams.append(stream)


class _FakeArray:
    _next_pointer = 0x1000

    def __init__(self, shape, dtype, value=None):
        self.shape = tuple(int(dimension) for dimension in shape)
        self.dtype = np.dtype(dtype)
        self.flags = SimpleNamespace(c_contiguous=True)
        self.value = np.empty(self.shape, dtype=self.dtype)
        if value is not None:
            self.value[...] = np.asarray(value, dtype=self.dtype)
        self.uploads: list[tuple[np.ndarray, object]] = []
        pointer = _FakeArray._next_pointer
        _FakeArray._next_pointer += max(0x100, int(self.value.nbytes))
        self.data = SimpleNamespace(ptr=pointer)

    def set(self, value, *, stream):
        copied = np.asarray(value, dtype=self.dtype).copy()
        self.value[...] = copied
        self.uploads.append((copied, stream))


class _FakeKernel:
    def __init__(self, symbol: str):
        self.symbol = symbol
        self.attributes = {"max_threads_per_block": 1024, "num_regs": 16}
        self.calls: list[tuple[object, object, object, object]] = []

    def __call__(self, grid, block, arguments, *, stream):
        self.calls.append((grid, block, arguments, stream))


class _FakeModule:
    def __init__(self, path: str):
        self.path = Path(path)
        self.ptx_at_load = self.path.read_text(encoding="utf-8")
        self.kernels: dict[str, _FakeKernel] = {}

    def get_function(self, symbol: str):
        kernel = _FakeKernel(symbol)
        self.kernels[symbol] = kernel
        return kernel


class _FakeCupy:
    def __init__(self, *, free_bytes: int = 1 << 40):
        self.device = _FakeContext()
        self.stream = _FakeStream()
        self.modules: list[_FakeModule] = []
        self.raw_module_arguments: list[dict[str, object]] = []
        self.cuda = SimpleNamespace(
            Device=lambda _: self.device,
            Stream=lambda **_: self.stream,
            Event=_FakeEvent,
            runtime=SimpleNamespace(memGetInfo=lambda: (free_bytes, free_bytes)),
            get_elapsed_time=lambda *_: 0.25,
        )

    def RawModule(self, **arguments):
        self.raw_module_arguments.append(arguments)
        module = _FakeModule(arguments["path"])
        self.modules.append(module)
        return module

    @staticmethod
    def array(value, *, dtype, order, copy):
        assert order == "C" and copy is True
        array = np.asarray(value)
        return _FakeArray(array.shape, dtype, array)

    @staticmethod
    def empty(shape, *, dtype, order):
        assert order == "C"
        return _FakeArray(shape, dtype)

    @staticmethod
    def asnumpy(value, *, stream, blocking):
        assert blocking is True
        return value.value.copy()


def _device_info(capability=(8, 6)) -> dict:
    return {
        "device_id": 0,
        "name": "fake-sm86",
        "compute_capability": list(capability),
        "total_memory_bytes": 1 << 40,
        "multiprocessor_count": 1,
        "driver_version": 13000,
        "runtime_version": 12090,
        "cupy_version": "fake",
        "supported_target": "cuda-sm86" if capability == (8, 6) else None,
    }


class MlirPtxRuntimeTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.program, cls.graph = _fixture()

    def test_non_program_is_rejected_before_cuda_is_touched(self):
        with patch("gac.mlir_ptx_runtime.cuda_device_info") as device_probe:
            with self.assertRaisesRegex(ValidationError, "MlirPtxProgram"):
                MlirPtxSession(object())
        device_probe.assert_not_called()

    def test_tampering_is_rejected_before_cupy_or_cuda_discovery(self):
        cases = {
            "abi": replace(self.program, abi_version=99),
            "target": replace(
                self.program,
                ptx=self.program.ptx.replace(".target sm_86", ".target sm_89"),
            ),
            "entry": replace(
                self.program,
                ptx=self.program.ptx.replace(PTX_ENTRY_SYMBOLS[0], "unexpected"),
            ),
            "ptx hash": replace(
                self.program, ptx=self.program.ptx + "// modified\n"
            ),
            "integrity hash": replace(self.program, integrity_sha256="0" * 64),
            "launch ABI": replace(
                self.program,
                launches=(
                    replace(self.program.launches[0], grid=(1, 1, 1)),
                    *self.program.launches[1:],
                ),
            ),
        }
        for component, altered in cases.items():
            with self.subTest(component=component):
                with (
                    patch("gac.mlir_ptx_runtime.cuda_device_info") as device_probe,
                    patch("gac.mlir_ptx_runtime._cupy") as cupy_probe,
                ):
                    with self.assertRaisesRegex(BackendError, "artifact"):
                        MlirPtxSession(altered)
                device_probe.assert_not_called()
                cupy_probe.assert_not_called()

    def test_wrong_device_is_rejected_before_module_loading(self):
        fake_cupy = _FakeCupy()
        with (
            patch(
                "gac.mlir_ptx_runtime.cuda_device_info",
                return_value=_device_info((8, 9)),
            ),
            patch("gac.mlir_ptx_runtime._cupy", return_value=fake_cupy) as probe,
        ):
            with self.assertRaisesRegex(DeviceUnavailableError, "8.6"):
                MlirPtxSession(self.program)
        probe.assert_not_called()
        self.assertFalse(fake_cupy.raw_module_arguments)

    def test_loads_validated_ptx_path_and_dispatches_exact_launch_plan(self):
        fake_cupy = _FakeCupy()
        with (
            patch(
                "gac.mlir_ptx_runtime.cuda_device_info",
                return_value=_device_info(),
            ),
            patch("gac.mlir_ptx_runtime._cupy", return_value=fake_cupy),
        ):
            session = MlirPtxSession(self.program)

        self.assertEqual(len(fake_cupy.raw_module_arguments), 1)
        arguments = fake_cupy.raw_module_arguments[0]
        self.assertEqual(set(arguments), {"path"})
        self.assertNotIn("code", arguments)
        self.assertNotIn("backend", arguments)
        self.assertEqual(fake_cupy.modules[0].ptx_at_load, self.program.ptx)
        self.assertTrue(Path(arguments["path"]).is_file())
        self.assertEqual(set(session._kernels), set(PTX_ENTRY_SYMBOLS))
        self.assertEqual(session.info["matmul_backend"]["cublas_launch_count"], 0)
        self.assertEqual(session.info["matmul_backend"]["nvrtc_launch_count"], 0)

        session._execute_launches()
        for launch in self.program.launches:
            kernel = session._kernels[launch.symbol]
            self.assertEqual(len(kernel.calls), 1)
            grid, block, values, stream = kernel.calls[0]
            self.assertEqual(grid, launch.grid)
            self.assertEqual(block, launch.block)
            self.assertEqual(
                values,
                tuple(session._values[name] for name in launch.inputs)
                + (session._values[launch.output],),
            )
            self.assertIs(stream, session._stream)

        ptx_path = Path(arguments["path"])
        session.close()
        session.close()
        self.assertFalse(ptx_path.exists())
        self.assertIsNone(session._module)
        self.assertIsNone(session._stream)
        self.assertFalse(session._kernels)

    def test_run_uses_one_stream_for_transfers_events_and_all_kernels(self):
        fake_cupy = _FakeCupy()
        with (
            patch(
                "gac.mlir_ptx_runtime.cuda_device_info",
                return_value=_device_info(),
            ),
            patch("gac.mlir_ptx_runtime._cupy", return_value=fake_cupy),
        ):
            with MlirPtxSession(self.program) as session:
                query = np.zeros(
                    self.graph.inputs["query"].shape, dtype=np.float32
                )
                result = session.run({"query": query})
                self.assertEqual(result.outputs["output"].shape, query.shape)
                self.assertEqual(result.gpu_stream_ms, 0.25)
                uploads = session._inputs["query"].uploads
                self.assertEqual(len(uploads), 1)
                self.assertIs(uploads[0][1], session._stream)
                for kernel in session._kernels.values():
                    self.assertEqual(len(kernel.calls), 1)
                    self.assertIs(kernel.calls[0][3], session._stream)

    def test_bound_device_values_must_match_static_nonaliasing_abi(self):
        session = MlirPtxSession.__new__(MlirPtxSession)
        session.program = self.program
        session._graph = self.program.graph
        referenced = {
            name
            for launch in self.program.launches
            for name in (*launch.inputs, launch.output)
        }
        session._values = {
            name: np.empty(
                self.program.graph.value_specs[name].shape,
                dtype=self.program.graph.value_specs[name].dtype,
            )
            for name in referenced
        }
        session._validate_actual_values()

        final = self.program.launches[-1]
        original_output = session._values[final.output]
        session._values[final.output] = session._values[final.inputs[2]]
        with self.assertRaisesRegex(BackendError, "undeclared .* alias"):
            session._validate_actual_values()

        session._values[final.output] = original_output
        first = self.program.launches[0]
        session._values[first.output] = np.empty(
            (1, 2500, 1024), dtype=np.float32
        )[:, :, ::2]
        with self.assertRaisesRegex(BackendError, "not C-contiguous"):
            session._validate_actual_values()

    def test_insufficient_memory_fails_and_removes_temporary_ptx(self):
        fake_cupy = _FakeCupy(free_bytes=1)
        with (
            patch(
                "gac.mlir_ptx_runtime.cuda_device_info",
                return_value=_device_info(),
            ),
            patch("gac.mlir_ptx_runtime._cupy", return_value=fake_cupy),
        ):
            with self.assertRaisesRegex(BackendError, "only 1 CUDA bytes free"):
                MlirPtxSession(self.program)
        self.assertEqual(len(fake_cupy.modules), 1)
        self.assertFalse(fake_cupy.modules[0].path.exists())


if __name__ == "__main__":
    unittest.main()
