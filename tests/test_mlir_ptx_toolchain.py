GPU_MLIR = """module attributes {gpu.container_module} {
  gpu.module @kernels {
    gpu.func @first() kernel {
      gpu.return
    }
  }
}
"""


def _ptx(
    *entries: str,
    target: str = "sm_86",
    address_size: int = 64,
    version: str = "7.1",
) -> str:
    declarations = "\n".join(
        f".visible .entry {entry}()\n{{\n  ret;\n}}" for entry in entries
    )
    return (
        "// Generated by the CPU-only test fixture\n"
        f".version {version}\n"
        f".target {target}\n"
        f".address_size {address_size}\n\n"
        f"{declarations}\n"
    )


def _mlir_escape(value: str) -> str:
    result: list[str] = []
    for byte in value.encode("utf-8"):
        if 0x20 <= byte < 0x7F and byte not in (ord('"'), ord("\\")):
            result.append(chr(byte))
        else:
            result.append(f"\\{byte:02X}")
    return "".join(result)


def _binary_mlir(ptx: str, *, symbol: str = "kernels") -> str:
    return (
        "module attributes {gpu.container_module} {\n"
        f"  gpu.binary @{symbol}  [#gpu.object<"
        '#nvvm.target<O = 3, chip = "sm_86", features = "+ptx71">, '
        f'assembly = "{_mlir_escape(ptx)}">]\n'
        "}\n"
    )


class Sm86PtxExtractionTests(unittest.TestCase):
    def test_decodes_hex_escapes_and_requires_the_exact_entry_set(self):
        source = _ptx("first", "second")
        binary_mlir = _binary_mlir(source)

        self.assertEqual(
            extract_sm86_ptx(
                binary_mlir, expected_entries=("second", "first")
            ),
            source,
        )

    def test_rejects_wrong_target_address_size_and_entry_set(self):
        cases = (
            (_binary_mlir(_ptx("first", version="9.0")), "version must be exactly 7.1"),
            (_binary_mlir(_ptx("first", target="sm_80")), "target must be exactly"),
            (_binary_mlir(_ptx("first", address_size=32)), "address size"),
            (_binary_mlir(_ptx("other")), "entry set"),
            (_binary_mlir(_ptx("first", "extra")), "entry set"),
            (
                _binary_mlir(
                    _ptx("first") + ".entry hidden()\n{\n  ret;\n}\n"
                ),
                "entry set",
            ),
            (
                _binary_mlir(_ptx("first").replace(".visible .entry", ".entry")),
                "must be visible",
            ),
            (_binary_mlir(_ptx("first") + "\x00"), "control character"),
        )
        for binary_mlir, message in cases:
            with self.subTest(message=message):
                with self.assertRaisesRegex(MlirPtxLoweringError, message):
                    extract_sm86_ptx(binary_mlir, expected_entries=("first",))

    def test_rejects_ambiguous_or_partially_lowered_artifacts(self):
        valid = _binary_mlir(_ptx("first"))
        cases = (
            (valid + _binary_mlir(_ptx("first"), symbol="other"), "gpu.binary"),
            (
                valid.replace(
                    "]\n}",
                    f', #gpu.object<#nvvm.target, assembly = "{_mlir_escape(_ptx("first"))}">]\n}}',
                ),
                "GPU object",
            ),
            (valid.replace("gpu.binary", "gpu.func @leftover\n  gpu.binary"), "still contains"),
        )
        for binary_mlir, message in cases:
            with self.subTest(message=message):
                with self.assertRaisesRegex(MlirPtxLoweringError, message):
                    extract_sm86_ptx(binary_mlir, expected_entries=("first",))

    def test_rejects_malformed_string_escapes(self):
        binary_mlir = (
            "module { gpu.binary @kernels [#gpu.object<#nvvm.target, "
            'assembly = "\\q">] }'
        )
        with self.assertRaisesRegex(MlirPtxLoweringError, "unsupported MLIR escape"):
            extract_sm86_ptx(binary_mlir, expected_entries=("first",))

    def test_expected_entry_contract_is_validated_before_parsing(self):
        valid = _binary_mlir(_ptx("first"))
        for entries, exception in (
            ((), ValueError),
            (("first", "first"), ValueError),
            (("bad entry",), ValueError),
            ("first", TypeError),
        ):
            with self.subTest(entries=entries):
                with self.assertRaises(exception):
                    extract_sm86_ptx(valid, expected_entries=entries)


class MlirToPtxInvocationTests(unittest.TestCase):
    def test_uses_fixed_official_pipeline_and_returns_provenance(self):
        observed: dict[str, object] = {}
        lowered = _binary_mlir(_ptx("first", "second"))

        def fake_run(argv, **kwargs):
            if argv[-1] == "--version":
                return subprocess.CompletedProcess(
                    argv,
                    0,
                    stdout="LLVM version 24.0.0git\n  Optimized build.\n",
                    stderr="",
                )
            observed["argv"] = argv
            observed["kwargs"] = kwargs
            input_path = Path(argv[1])
            output_path = Path(argv[argv.index("-o") + 1])
            observed["input"] = input_path
            observed["output"] = output_path
            self.assertEqual(input_path.read_text(encoding="utf-8"), GPU_MLIR)
            output_path.write_text(lowered, encoding="utf-8")
            return subprocess.CompletedProcess(argv, 0, stdout="", stderr="")

        revision = "765392a6b4498f1dc57233f03a31b87462fdef01"
        with (
            mock.patch("gac.mlir_toolchain.subprocess.run", side_effect=fake_run),
            mock.patch(
                "gac.mlir_toolchain.probe_mlir_opt_source_revision",
                return_value=revision,
            ),
        ):
            artifact = lower_gpu_mlir_to_ptx(
                GPU_MLIR,
                expected_entries=("first", "second"),
                command=("mock-mlir-opt",),
                timeout=9,
            )

        self.assertEqual(artifact.binary_mlir, lowered)
        self.assertEqual(artifact.lowered_mlir, lowered)
        self.assertEqual(artifact.ptx, _ptx("first", "second"))
        self.assertEqual(
            artifact.source_sha256,
            hashlib.sha256(GPU_MLIR.encode("utf-8")).hexdigest(),
        )
        self.assertEqual(artifact.entries, ("first", "second"))
        self.assertEqual(artifact.target_chip, "sm_86")
        self.assertEqual(artifact.target_features, "+ptx71")
        self.assertEqual(artifact.ptx_version, "7.1")
        self.assertEqual(artifact.mlir_opt_source_revision, revision)
        self.assertIn("LLVM version 24.0.0git", artifact.mlir_opt_version)
        self.assertIn(SM86_NVVM_PIPELINE, artifact.command)
        self.assertIn("--verify-each", artifact.command)
        self.assertIs(observed["kwargs"]["shell"], False)
        self.assertEqual(observed["kwargs"]["encoding"], "utf-8")
        self.assertEqual(observed["kwargs"]["errors"], "replace")
        self.assertEqual(observed["kwargs"]["timeout"], 9.0)
        self.assertFalse(observed["input"].exists())
        self.assertFalse(observed["output"].exists())

    def test_real_cpu_child_process_receives_pipeline_and_writes_artifact(self):
        lowered = _binary_mlir(_ptx("first"))
        with tempfile.TemporaryDirectory() as directory:
            script = Path(directory) / "mock_mlir_opt.py"
            script.write_text(
                """import pathlib
import sys

args = sys.argv[1:]
if args == ["--version"]:
    print("LLVM version 24.0.0git")
    raise SystemExit(0)
if "--verify-each" not in args:
    raise SystemExit(10)
if not any(arg.startswith("--gpu-lower-to-nvvm-pipeline=") for arg in args):
    raise SystemExit(11)
output = pathlib.Path(args[args.index("-o") + 1])
input_path = pathlib.Path(args[0])
if "gpu.module" not in input_path.read_text(encoding="utf-8"):
    raise SystemExit(12)
output.write_text(LOWERED, encoding="utf-8")
""".replace("LOWERED", repr(lowered)),
                encoding="utf-8",
            )
            artifact = lower_gpu_mlir_to_ptx(
                GPU_MLIR,
                expected_entries=("first",),
                command=(sys.executable, str(script)),
            )

        self.assertEqual(artifact.ptx, _ptx("first"))
        self.assertIsNone(artifact.mlir_opt_source_revision)

    def test_lowering_failure_timeout_and_missing_output_are_actionable(self):
        version = subprocess.CompletedProcess(
            [], 0, stdout="LLVM version 24.0.0git\n", stderr=""
        )
        stderr = "start:" + "x" * (MAX_STDERR_CHARS * 3) + ":end"
        failed = subprocess.CompletedProcess([], 6, stdout="", stderr=stderr)
        with mock.patch(
            "gac.mlir_toolchain.subprocess.run", side_effect=(version, failed)
        ):
            with self.assertRaises(MlirPtxLoweringError) as raised:
                lower_gpu_mlir_to_ptx(
                    GPU_MLIR,
                    expected_entries=("first",),
                    command=("mock-mlir-opt", "wrapper"),
                )
        self.assertIn("status 6", str(raised.exception))
        self.assertIn("stderr truncated", str(raised.exception))
        self.assertLess(len(str(raised.exception)), MAX_STDERR_CHARS + 300)

        timeout = subprocess.TimeoutExpired(
            ["mock-mlir-opt"], 0.01, stderr="timeout diagnostic"
        )
        with mock.patch(
            "gac.mlir_toolchain.subprocess.run", side_effect=(version, timeout)
        ):
            with self.assertRaisesRegex(MlirPtxLoweringError, "timed out"):
                lower_gpu_mlir_to_ptx(
                    GPU_MLIR,
                    expected_entries=("first",),
                    command=("mock-mlir-opt", "wrapper"),
                    timeout=0.01,
                )

        success = subprocess.CompletedProcess([], 0, stdout="", stderr="note")
        with mock.patch(
            "gac.mlir_toolchain.subprocess.run", side_effect=(version, success)
        ):
            with self.assertRaisesRegex(MlirPtxLoweringError, "readable output"):
                lower_gpu_mlir_to_ptx(
                    GPU_MLIR,
                    expected_entries=("first",),
                    command=("mock-mlir-opt", "wrapper"),
                )

    def test_argument_validation(self):
        with self.assertRaisesRegex(ValueError, "non-empty"):
            lower_gpu_mlir_to_ptx(
                " ", expected_entries=("first",), command=("tool",)
            )
        with self.assertRaisesRegex(ValueError, "mutually exclusive"):
            lower_gpu_mlir_to_ptx(
                GPU_MLIR,
                expected_entries=("first",),
                mlir_opt="tool",
                command=("other",),
            )
        for timeout in (0, -1, float("inf"), float("nan"), True):
            with self.subTest(timeout=timeout):
                with self.assertRaisesRegex(ValueError, "timeout"):
                    lower_gpu_mlir_to_ptx(
                        GPU_MLIR,
                        expected_entries=("first",),
                        command=("tool",),
                        timeout=timeout,
                    )

    @unittest.skipUnless(os.name == "nt", "WSL command wrapping is Windows-specific")
    def test_wsl_lowering_uses_argv_only_and_linux_paths(self):
        lowered = _binary_mlir(_ptx("first"))
        observed: dict[str, object] = {}

        def fake_run(argv, **kwargs):
            if argv[-1] == "--version":
                return subprocess.CompletedProcess(
                    argv, 0, stdout="LLVM version 24.0.0git\n", stderr=""
                )
            if argv[4] == "cat":
                return subprocess.CompletedProcess(argv, 1, stdout="", stderr="missing")
            observed["argv"] = argv
            observed["kwargs"] = kwargs
            output_text = argv[argv.index("-o") + 1]
            drive, *parts = output_text.removeprefix("/mnt/").split("/")
            Path(f"{drive.upper()}:\\", *parts).write_text(lowered, encoding="utf-8")
            return subprocess.CompletedProcess(argv, 0, stdout="", stderr="")

        with mock.patch("gac.mlir_toolchain.subprocess.run", side_effect=fake_run):
            artifact = lower_gpu_mlir_to_ptx(
                GPU_MLIR,
                expected_entries=("first",),
                mlir_opt="/home/user/build/bin/mlir-opt",
                use_wsl=True,
                wsl_distribution="Ubuntu-24.04",
            )

        self.assertEqual(
            observed["argv"][:5],
            [
                "wsl.exe",
                "-d",
                "Ubuntu-24.04",
                "--",
                "/home/user/build/bin/mlir-opt",
            ],
        )
        self.assertRegex(observed["argv"][5], r"^/mnt/[a-z]/")
        self.assertIs(observed["kwargs"]["shell"], False)
        self.assertEqual(artifact.entries, ("first",))


